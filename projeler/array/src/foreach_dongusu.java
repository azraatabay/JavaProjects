public class foreach_dongusu {
    public static void main(String[] args){
        String[] array = {"elma", "armut", "erik"};
        for (String a : array){
            System.out.println(a);
        }

        int[] array2 = {1,2,3,4,5,6,7,8};
        for (int i : array2){
            System.out.println(i);
        }


    }
}
